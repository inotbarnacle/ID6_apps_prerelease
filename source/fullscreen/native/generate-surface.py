"""Generate catalogue strings, controls, and the MHD logo for the QNX surface."""
import json
from pathlib import Path
from features import MHD, BEAMER, UPDATES
from PIL import Image

root = Path(__file__).resolve().parents[1]
items = json.loads((root / 'catalog.json').read_text())
output = root / 'native/generated/surface_assets.h'
with output.open('w') as file:
    file.write('/* Generated by generate-surface.py. */\n')
    file.write('static const char* const surface_titles[] = {\n')
    for item in items:
        file.write('    ' + json.dumps(item['name'], ensure_ascii=True) + ',\n')
    file.write('};\n')
    file.write('struct feature_button { const char *title; int action, x, y, width, height; };\n')
    for name, buttons in [('mhd_controls', MHD), ('beamer_controls', BEAMER), ('usb_controls', UPDATES)]:
        file.write(f'static const struct feature_button {name}[] = {{\n')
        for title, *values in buttons:
            file.write('    {' + json.dumps(title) + ', ' + ', '.join(map(str, values)) + '},\n')
        file.write('};\n')

with Image.open(root / 'native/images/mhd-logo.png') as source:
    logo = source.convert('RGBA').resize((268, 36), Image.Resampling.LANCZOS)
with (output.parent / 'mhd_logo.h').open('w') as file:
    file.write('/* Generated by generate-surface.py from the standalone MHD+ Suite logo. */\n')
    file.write(f'enum {{ mhd_logo_width = {logo.width}, mhd_logo_height = {logo.height} }};\n')
    file.write('static const unsigned char mhd_logo_rgba[] = {\n')
    pixels = logo.tobytes()
    for index in range(0, len(pixels), 32):
        file.write('    ' + ', '.join(map(str, pixels[index:index+32])) + ',\n')
    file.write('};\n')
