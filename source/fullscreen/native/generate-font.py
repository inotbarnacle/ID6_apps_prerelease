"""Rasterize the OFL Barlow Condensed face into a compact display atlas."""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

root = Path(__file__).resolve().parent
with (root / "generated" / "library_font.h").open("w") as out:
    out.write("/* Generated by generate-font.py. Barlow Condensed, SIL OFL. */\n")
    out.write("struct library_glyph { unsigned offset; unsigned char width, advance; };\n")
    for size, height in [(24, 29), (64, 72)]:
        font = ImageFont.truetype(str(root / "fonts" / "BarlowCondensed-SemiBold.ttf"), size)
        glyphs, pixels = [], bytearray()
        for code in (*range(32, 127), 176):
            char = chr(code)
            left, _top, right, _bottom = font.getbbox(char)
            width = max(1, right - min(0, left))
            cell = Image.new("L", (width, height))
            ImageDraw.Draw(cell).text((-min(0, left), -size // 8), char, font=font, fill=255)
            glyphs.append((len(pixels), width, max(1, round(font.getlength(char)))))
            pixels.extend(cell.tobytes())
        out.write(f"static const struct library_glyph glyph_{size}[] = {{\n")
        for glyph in glyphs:
            out.write("    {%d, %d, %d},\n" % glyph)
        out.write("};\n")
        out.write(f"static const unsigned char ink_{size}[] = {{\n")
        for i in range(0, len(pixels), 32):
            out.write("    " + ",".join(map(str, pixels[i:i+32])) + ",\n")
        out.write("};\n")
