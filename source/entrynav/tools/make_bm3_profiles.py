#!/usr/bin/env python3
"""Generate src/bm3_profiles.h from cauliflowermossgrape's bm3_profiles.js (MIT, third-party/cauliflowermossgrape-LICENSE).

The profiles hold only ROM identifiers and DME memory addresses, no tune contents. Regenerate after updating from
upstream, and record the commit:

    python3 tools/make_bm3_profiles.py PATH/TO/bm3_profiles.js COMMIT
"""

import json
import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "src" / "bm3_profiles.h"


def layouts(source):
    match = re.search(r"const layouts = (\[.*?\n\]);", source, re.S)
    if not match:
        raise SystemExit("no 'const layouts = [...]' in the file")
    return json.loads(match.group(1))


def hex32(value):
    if not re.fullmatch(r"[0-9A-Fa-f]{8}", value):
        raise SystemExit(f"invalid address {value!r}")
    return "0x" + value.upper()


def main(argv):
    if len(argv) != 3:
        raise SystemExit(__doc__)
    source, commit = Path(argv[1]).read_text(), argv[2]
    if not re.fullmatch(r"[0-9a-f]{40}", commit):
        raise SystemExit("give the full 40-character commit")
    rows, seen = [], set()
    for layout in layouts(source):
        command = layout["wmbaCmd"].lower()
        if command not in ("3d", "3e"):
            raise SystemExit(f"unsupported memory-write command {command}")
        factor = layout["factor"]
        if not isinstance(factor, int) or not 0 < factor * 12 <= 127:
            raise SystemExit(f"invalid burble factor {factor}")
        for rom in layout["roms"]:
            if not re.fullmatch(r"[A-Z0-9]{6,9}", rom) or rom in seen:
                raise SystemExit(f"invalid or repeated ROM {rom!r}")
            seen.add(rom)
            rows.append(f'    {{"{rom}", {hex32(layout["mapSwActAddr"])}, {hex32(layout["burbleActAddr"])}, '
                        f'{hex32(layout["timingAddress"])}, {factor}, 0x{command.upper()}}},')
    OUT.write_text(f"""/* Generated by tools/make_bm3_profiles.py from cauliflowermossgrape's bm3_profiles.js
 * at {commit} (MIT, third-party/cauliflowermossgrape-LICENSE),
 * itself from BM3 Live by ezl0l. ROM identifiers and DME addresses only. A listed ROM is not a compatibility
 * certification. Do not edit by hand. */
#ifndef BM3_PROFILES_H
#define BM3_PROFILES_H

#include "bm3.h"

static const bm3_profile bm3_profiles[] = {{
{chr(10).join(rows)}
}};
#define BM3_PROFILE_COUNT (sizeof bm3_profiles / sizeof bm3_profiles[0])

#endif
""", newline="\n")  # the same bytes on Windows and Linux
    print(f"{OUT}: {len(rows)} ROMs")


if __name__ == "__main__":
    main(sys.argv)
